"""Circuit Solver Module for simulating linear and non-linear circuits.

This module provides the core mathematical solvers for the Modified Nodal
Analysis (MNA) equations generated by the physical circuit components. It 
implements both standard direct sparse LU factorization and an advanced 
Explicit Woodbury Strategy for O(1) localized large-change sensitivity analysis. 

Furthermore, it features a highly robust, cascading Newton-Raphson nonlinear 
solver with built-in failsafe algorithms (Damped Stepping, Source Stepping, 
and GMIN Stepping) to guarantee convergence for volatile non-linear systems.
"""

import numpy as np
import scipy.sparse as sp
from scipy.sparse.linalg import spsolve, splu

class ConvergenceError(Exception):
    """Raised when a nonlinear solving strategy fails to converge within tolerances."""
    pass

# =========================================================================
# LINEAR SOLVERS & UTILITIES
# =========================================================================

def solve_lu(g):
    """Performs SuperLU factorization on a sparse admittance matrix.

    Args:
        g (scipy.sparse.csc_matrix): The global MNA admittance matrix in 
            Compressed Sparse Column format.

    Returns:
        scipy.sparse.linalg.SuperLU: The factorized LU object, which can be 
        cached and reused to quickly solve multiple RHS vectors without 
        re-inverting the matrix.
    """
    return splu(g)

def get_node_and_branch_currents(lu, sources):
    """Solves the linear system using a pre-computed LU factorization.

    Args:
        lu (scipy.sparse.linalg.SuperLU): The factorized matrix object.
        sources (numpy.ndarray): The Right-Hand Side (RHS) vector containing 
            independent and equivalent source currents/voltages.

    Returns:
        numpy.ndarray: The resolved state vector containing absolute node 
        voltages and auxiliary branch currents.
    """
    return lu.solve(sources)

def solve_linear_circuit(y, sources):
    """Solves a complete linear circuit equation in a single pass.

    This acts as a convenience wrapper around `solve_lu` and 
    `get_node_and_branch_currents`.

    Args:
        y (scipy.sparse.csc_matrix): The full MNA admittance matrix.
        sources (numpy.ndarray): The RHS source vector.

    Returns:
        tuple[scipy.sparse.linalg.SuperLU, numpy.ndarray]: A tuple containing 
        the cached LU factorization object and the solved state vector.
    """
    lu = solve_lu(y)
    vi = get_node_and_branch_currents(lu, sources)
    return lu, vi

def solve_adjoint(lu, target, circuit):
    """Solves the transposed matrix equation for Adjoint sensitivity analysis.

    Injects a mathematical impulse (1.0) at the target output node and solves 
    the system backward using the cached forward LU factorization.

    Args:
        lu (scipy.sparse.linalg.SuperLU): Cached LU factorization from the 
            forward simulation pass.
        target (str or int): The netlist name or integer ID of the objective 
            output node.
        circuit (Circuit): The active circuit orchestrator, used for node 
            index lookups.

    Returns:
        numpy.ndarray: The adjoint state vector (Psi/Phi) mapping the sensitivity 
        of the target output to every node in the circuit.
    """
    d = np.zeros(circuit.total_dim)
    idx = circuit.get_idx(target)
    
    if idx is not None:
        d[idx] = 1.0
        
    return lu.solve(d, trans='T')

