# SOLVER STRATEGIES (For Parameter Sweeps and Large Change Analysis)
# =========================================================================

class StandardDirectStrategy:
    """The traditional solving approach using full LU factorization per step."""
    
    def solve_step(self, circuit, v_k, domain, t, dt, v_prev, method, gmin=0.0, source_scale=1.0):
        """Builds and solves the sparse global matrix natively.

        Args:
            circuit (Circuit): The active circuit orchestrator.
            v_k (numpy.ndarray): The current Newton-Raphson iteration guess.
            domain (str): The simulation domain ('static', 'time', 'frequency').
            t (float): The current simulation time in seconds.
            dt (float): The integration time step in seconds.
            v_prev (numpy.ndarray): The converged state from the previous time step.
            method (str): The integration method ('TR' or 'BE').
            gmin (float, optional): Artificial ground conductance to inject. Defaults to 0.0.
            source_scale (float, optional): Multiplier for independent sources. Defaults to 1.0.

        Returns:
            tuple[scipy.sparse.linalg.SuperLU, numpy.ndarray]: The LU factorization 
            and the resulting evaluated state vector.
        """
        # 1. Build the full global Y matrix and J vector
        Y_iter, J_iter = circuit.build_system(
            domain=domain, t=t, dt=dt, v_prev=v_prev, v_k=v_k, method=method
        )
        
        # 2. Apply Solver Interventions
        if source_scale != 1.0:
            J_iter *= source_scale
            
        if gmin > 0.0:
            gmin_matrix = sp.diags([gmin], [0], shape=(circuit.total_dim, circuit.total_dim))
            Y_iter = Y_iter + gmin_matrix
            
        # 3. LU Factorize the full O(N x N) matrix
        lu = splu(Y_iter.tocsc())
        v_new = lu.solve(J_iter)
        
        return lu, v_new

class ExplicitWoodburyStrategy:
    
    def __init__(self, circuit, param_names, lu_base, v_nom, dp_array=None):
        self.lu_base = lu_base
        self.v_nom = v_nom  
        self.comp_to_shifts = {}
        swept_comps = set()
        
        if dp_array is not None:
            for p, dp in zip(param_names, dp_array):
                comp = circuit.param_to_component_map[p]
                swept_comps.add(comp)
                if comp not in self.comp_to_shifts:
                    self.comp_to_shifts[comp] = {}
                self.comp_to_shifts[comp][p] = dp

        nl_comps = set(getattr(circuit, '_nl_comps', []))
        self.active_components = list(swept_comps.union(nl_comps))
        
        self.N = circuit.total_dim
        
        self.comp_indices = {}
        self.k = 0
        
        for comp in self.active_components:
            rank = getattr(comp, 'rank', 1) # Default to 1 if not specified
            self.comp_indices[comp] = (self.k, self.k + rank)
            self.k += rank
            
        self.P = np.zeros((self.N, self.k))
        self.Q = np.zeros((self.N, self.k))
        
        for comp in self.active_components:
            start_idx, _ = self.comp_indices[comp]
            comp.stamp_PQ(self.P, self.Q, start_idx)

        self.X = self.lu_base.solve(self.P)
        self.QT_X = self.Q.T @ self.X


    def solve_step(self, circuit, v_k, domain, t, dt, v_prev, method, gmin=0.0, source_scale=1.0):
        """Solves the system using the Woodbury matrix identity instead of LU.

        If GMIN stepping modifies the global topology, this method safely falls 
        back to the `StandardDirectStrategy` for the current step.

        Args:
            circuit (Circuit): The active circuit orchestrator.
            v_k (numpy.ndarray): The current Newton-Raphson iteration guess.
            domain (str): The simulation domain ('static', 'time', 'frequency').
            t (float): The current simulation time in seconds.
            dt (float): The integration time step in seconds.
            v_prev (numpy.ndarray): The converged state from the previous time step.
            method (str): The integration method ('TR' or 'BE').
            gmin (float, optional): Artificial ground conductance to inject. Defaults to 0.0.
            source_scale (float, optional): Multiplier for independent sources. Defaults to 1.0.

        Returns:
            tuple[scipy.sparse.linalg.SuperLU, numpy.ndarray]: The cached baseline 
            LU factorization and the newly calculated state vector.
        """
        if gmin > 0.0:
            fallback = StandardDirectStrategy()
            return fallback.solve_step(circuit, v_k, domain, t, dt, v_prev, method, gmin, source_scale)

        # 1. RHS Extraction (Bypasses sparse matrix allocation!)
        J_iter = circuit.build_rhs_only(
            domain=domain, t=t, dt=dt, v_prev=v_prev, v_k=v_k, method=method
        )
        
        if source_scale != 1.0:
            J_iter *= source_scale

        delta_G = np.zeros((self.k, self.k), dtype=complex if domain=="frequency" else float)
        
        for comp in self.active_components:
            start_idx, end_idx = self.comp_indices[comp]
            shifts_dict = self.comp_to_shifts.get(comp, {})
            
            # Fetch the shift (Could be a scalar for CL, or a 2x2 matrix for MOSFET)
            val = comp.get_delta_y(
                shifts=shifts_dict, V_nom=self.v_nom, V_k=v_k, 
                domain=domain, dt=dt, method=method
            )

            if isinstance(val, np.ndarray):
                delta_G[start_idx:end_idx, start_idx:end_idx] = val
            else:
                delta_G[start_idx, start_idx] = val

        # 3. Standard Woodbury Math
        V_lin = self.lu_base.solve(J_iter)
        QT_V = self.Q.T @ V_lin
        
        M = np.eye(self.k) + delta_G @ self.QT_X
        inv_M = np.linalg.inv(M)
        dV = -self.X @ (inv_M @ (delta_G @ QT_V))
        
        return self.lu_base, V_lin + dV

