class NonlinearSolver:
    """Cascading Newton-Raphson nonlinear solver.

    Tries to solve the nonlinear circuit using standard Newton-Raphson. If it 
    fails due to singular matrices or oscillation, it progressively cascades 
    through slower but more robust strategies to force convergence.
    """

    def __init__(self, circuit, max_iter=100, tol=1e-6, print_stuff=True):
        """Initializes the Nonlinear Solver orchestrator.

        Args:
            circuit (Circuit): The main circuit orchestrator.
            max_iter (int, optional): Max iterations per NR attempt. Defaults to 100.
            tol (float, optional): Voltage error tolerance in Volts. Defaults to 1e-6.
            print_stuff (bool, optional): Toggles console logging output. Defaults to True.
        """
        self.circuit = circuit
        self.max_iter = max_iter
        self.tol = tol
        self.print_stuff = print_stuff

    def solve(self, v_ini, domain="static", t=0.0, dt=0.0, v_prev=None, method="TR", strategy=None):
        """The Master Routing Method. Cascades through fallback options if NR fails.

        Args:
            v_ini (numpy.ndarray): The initial voltage guess vector.
            domain (str, optional): The simulation domain. Defaults to "static".
            t (float, optional): Current simulation time in seconds. Defaults to 0.0.
            dt (float, optional): Current time step size. Defaults to 0.0.
            v_prev (numpy.ndarray, optional): Previous converged voltage state. Defaults to None.
            method (str, optional): Integration method ("TR" or "BE"). Defaults to "TR".
            strategy (object, optional): An injected strategy instance (e.g., ExplicitWoodburyStrategy). 
                Defaults to StandardDirectStrategy if None is provided.

        Returns:
            tuple[scipy.sparse.linalg.SuperLU, numpy.ndarray]: The final factorized 
            matrix and the converged solution array.

        Raises:
            RuntimeError: If all convergence strategies fail.
        """
        if strategy is None:
            strategy = StandardDirectStrategy()
            
        ctx = {
            "domain": domain, "t": t, "dt": dt, 
            "v_prev": v_prev, "method": method, "strategy": strategy
        }

        try:
            if self.print_stuff: print("\n--- Attempting Standard Newton-Raphson ---")
            return self._nr_core(v_ini, alpha=1.0, **ctx)
        except ConvergenceError:
            pass

        try:
            if self.print_stuff: print("\n--- Fallback 1: Damped Newton-Raphson ---")
            return self._nr_core(v_ini, alpha=0.25, **ctx)
        except ConvergenceError:
            pass

        try:
            if self.print_stuff: print("\n--- Fallback 2: Source Stepping ---")
            return self._source_stepping(v_ini, **ctx)
        except ConvergenceError:
            pass

        try:
            if self.print_stuff: print("\n--- Fallback 3: GMIN Stepping ---")
            return self._gmin_stepping(v_ini, **ctx)
        except ConvergenceError:
            raise RuntimeError("CRITICAL: All convergence methods failed.")

    def _nr_core(self, v_guess, domain="static", t=0.0, dt=0.0, v_prev=None, method="TR", alpha=1.0, gmin=0.0, source_scale=1.0, strategy=None):
        """The pure mathematical Newton-Raphson iterative loop.

        Args:
            v_guess (numpy.ndarray): Starting guess for this iteration sequence.
            domain (str): The simulation domain.
            t (float): Current simulation time.
            dt (float): Current time step.
            v_prev (numpy.ndarray): Previous converged voltage state.
            method (str): Integration method.
            alpha (float, optional): Damping multiplier. Defaults to 1.0.
            gmin (float, optional): Artificial ground conductance. Defaults to 0.0.
            source_scale (float, optional): Multiplier for the RHS vector. Defaults to 1.0.
            strategy (object): The dependency-injected matrix resolution strategy.

        Returns:
            tuple[scipy.sparse.linalg.SuperLU, numpy.ndarray]: The finalized LU 
            factorization and the converged vector.

        Raises:
            ConvergenceError: If maximum iterations are reached or matrix becomes singular.
        """
        v_k = v_guess.copy()

        for i in range(self.max_iter):
            # Delegate entirely to the injected strategy
            try:
                lu, v_new = strategy.solve_step(
                    self.circuit, v_k, domain, t, dt, v_prev, method, gmin, source_scale
                )
            except Exception:
                raise ConvergenceError("Matrix became singular.")

            delta_v = np.abs(v_new - v_k)
            max_error = np.max(delta_v)

            max_step = 0.3
            delta_v = v_new - v_k
            delta_v_clamped = np.clip(delta_v, -max_step, max_step)

            v_k = v_k + alpha * delta_v_clamped

            if max_error < self.tol:
                if self.print_stuff: 
                    print(f"  -> Converged in {i+1} iterations (alpha={alpha}, gmin={gmin:.1e}).")
                return lu, v_k

        raise ConvergenceError(f"Failed to converge after {self.max_iter} iterations.")

    def _source_stepping(self, v_guess, **ctx):
        """Slowly scales up independent sources from 10% to 100% to aid convergence."""
        num_steps = 10
        ramp = np.linspace(1.0/num_steps, 1.0, num_steps)
        v_k = v_guess.copy()
        lu = None
        for k in ramp:
            if self.print_stuff: print(f"  Source Step: {k*100:.0f}%")
            lu, v_k = self._nr_core(v_guess=v_k, alpha=1.0, source_scale=k, **ctx)
        return lu, v_k

    def _gmin_stepping(self, v_guess, **ctx):
        """Starts with a massive 1/100 Ohm conductance to ground, stepping down to 1e-12."""
        gmin_steps = np.logspace(-2, -12, num=10)
        v_k = v_guess.copy()
        lu = None
        for g in gmin_steps:
            if self.print_stuff: print(f"  GMIN Step: {g:.1e} Siemens")
            lu, v_k = self._nr_core(v_guess=v_k, alpha=1.0, gmin=g, **ctx)
        if self.print_stuff: print("  Final GMIN Cleanup Pass (0 Siemens)")
        return self._nr_core(v_guess=v_k, alpha=1.0, gmin=0.0, **ctx)
